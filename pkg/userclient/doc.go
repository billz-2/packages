// Package userclient - общий клиент для получения пользователя по id из
// billz_user_service: сначала Redis, при промахе - HTTP GET /v1/user/{id}.
//
// Два инварианта, которые нельзя нарушать:
//
//  1. Пакет НИКОГДА не пишет в Redis. Кеш прогревает сам billz_user_service,
//     когда обслуживает GET /v1/user/:id (api/v1/user.go:89). Второй писатель
//     рискует разойтись с ним в формате сериализации без всякой выгоды.
//     Поэтому клиент внутри держит Redis как узкий интерфейс только на чтение
//     (cacheReader: Get + MGet) - записи нет даже технически.
//
//  2. Ключ кеша обязан совпадать с billz_user_service/config.GetUserCacheKey,
//     то есть "user:<uuid>". Свой ключ, свой TTL или собственный кеш в процессе
//     потребителя не инвалидируются при изменении пользователя (user_service
//     чистит ключ в app/service/user.go:430,498, events/user_service/user/listener.go:246,
//     app/service/company.go:307, app/service/shop.go:172,227) и будут отдавать
//     устаревшие данные - например, старый язык пользователя.
//
// Redis - оптимизация, а не зависимость: nil-клиент или ошибка Redis
// деградируют в HTTP-запрос с warning в лог, но не в ошибку вызова.
